from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).with_name("planner-d.ts")


def words(*parts: str) -> int:
    return len(" ".join(parts).split())


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def fmt_paras(paras: list[str]) -> str:
    return "\n".join(f'          "{esc(p)}",' for p in paras)


def fmt_faqs(faqs: list[tuple[str, str]]) -> str:
    return "\n".join(f'      {{ q: "{esc(q)}", a: "{esc(a)}" }},' for q, a in faqs)


def article_ts(a: dict) -> str:
    sections_ts = []
    for sec in a["sections"]:
        head = f'        heading: "{esc(sec["heading"])}",\n' if sec.get("heading") else ""
        sections_ts.append(
            "      {\n"
            f"{head}"
            "        paragraphs: [\n"
            f"{fmt_paras(sec['paragraphs'])}\n"
            "        ],\n"
            "      }"
        )
    sections_joined = ",\n".join(sections_ts)
    kw = ", ".join(f'"{esc(k)}"' for k in a["keywords"])
    return f"""  make({{
    ...published,
    slug: "{a["slug"]}",
    title: "{esc(a["title"])}",
    description:
      "{esc(a["description"])}",
    keywords: [{kw}],
    category: "{esc(a["category"])}",
    image: "/images/articles/{a["slug"]}.png",
    imageAlt: "{esc(a["imageAlt"])}",
    sections: [
{sections_joined},
    ],
    faqs: [
{fmt_faqs(a["faqs"])}
    ],
  }})"""


def count_article(a: dict) -> int:
    parts: list[str] = []
    for sec in a["sections"]:
        parts.extend(sec["paragraphs"])
    for q, ans in a["faqs"]:
        parts.append(q)
        parts.append(ans)
    return words(*parts)


