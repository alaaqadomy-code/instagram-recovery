# Extra paragraphs appended to each article (heading -> paras) plus optional new sections.
# Target: bring each piece into 900–1100 whitespace tokens.


def expand(a: dict) -> dict:
    slug = a["slug"]
    extra = EXTRAS.get(slug)
    if not extra:
        return a
    # append paras to matching headings
    for sec in a["sections"]:
        h = sec.get("heading")
        if h and h in extra.get("by_heading", {}):
            sec["paragraphs"].extend(extra["by_heading"][h])
    # open section
    if extra.get("open"):
        a["sections"][0]["paragraphs"].extend(extra["open"])
    # new sections before faqs conceptually: insert before last section or append
    for ns in extra.get("new_sections", []):
        a["sections"].append(ns)
    # extra faqs
    for faq in extra.get("faqs", []):
        a["faqs"].append(faq)
    return a


def P(*paras: str) -> list[str]:
    return list(paras)


EXTRAS: dict[str, dict] = {}


def E(slug: str, **kwargs) -> None:
    EXTRAS[slug] = kwargs


